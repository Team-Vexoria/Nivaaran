// Real-time Translate Helper Function
export function tr(text: string | undefined | null, lang: SupportedLanguage = 'en'): string {
  if (!text) return '';
  if (lang === 'en') return text;

  const trimmed = text.trim();
  
  // 1. Direct exact match from local dictionary
  if (DICTIONARY[trimmed] && DICTIONARY[trimmed][lang]) {
    return DICTIONARY[trimmed][lang]!;
  }

  // 2. Case-insensitive lookup
  const key = Object.keys(DICTIONARY).find(k => k.toLowerCase() === trimmed.toLowerCase());
  if (key && DICTIONARY[key] && DICTIONARY[key][lang]) {
    return DICTIONARY[key][lang]!;
  }

  // 3. Known phrase / word replacement fallbacks
  let translated = trimmed;
  Object.keys(DICTIONARY).forEach(k => {
    if (DICTIONARY[k] && DICTIONARY[k][lang] && translated.includes(k)) {
      translated = translated.replace(new RegExp(k, 'g'), DICTIONARY[k][lang]!);
    }
  });

  return translated;
}
